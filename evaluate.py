def run_evaluation():
    agent = TextToSQLAgent()

    print(f"Running evaluation on {len(TEST_QUESTIONS)} test cases...")
    results_with_retry = []
    results_without_retry = []

    for i, test in enumerate(TEST_QUESTIONS):
        query = test["query"]

        # Run WITH retry (max_retries = 3)
        agent.max_retries = 3
        res_retry = agent.run(query)

        # Run WITHOUT retry (max_retries = 0)
        agent.max_retries = 0
        res_no_retry = agent.run(query)

        results_with_retry.append({
            "query": query,
            "success": res_retry.execution_success and res_retry.validation_result,
            "retries": res_retry.retry_count,
            "error": res_retry.error_message or res_retry.validation_message
        })

        results_without_retry.append({
            "query": query,
            "success": res_no_retry.execution_success and res_no_retry.validation_result,
            "retries": res_no_retry.retry_count,
            "error": res_no_retry.error_message or res_no_retry.validation_message
        })

    success_with = sum(1 for r in results_with_retry if r["success"])
    success_without = sum(1 for r in results_without_retry if r["success"])

    print("\n" + "="*50)
    print("EVALUATION RESULTS SUMMARY")
    print("="*50)
    print(f"Total Test Questions: {len(TEST_QUESTIONS)}")
    print(f"Success WITH Retries: {success_with}/{len(TEST_QUESTIONS)} ({success_with/len(TEST_QUESTIONS)*100:.1f}%)")
    print(f"Success WITHOUT Retries: {success_without}/{len(TEST_QUESTIONS)} ({success_without/len(TEST_QUESTIONS)*100:.1f}%)")
    print("="*50)

    report = {
        "total_questions": len(TEST_QUESTIONS),
        "success_with_retries": success_with,
        "success_without_retries": success_without,
        "accuracy_with_retries_pct": success_with/len(TEST_QUESTIONS)*100,
        "accuracy_without_retries_pct": success_without/len(TEST_QUESTIONS)*100,
        "details_with_retries": results_with_retry,
        "details_without_retries": results_without_retry
    }

    report_path = os.path.join(os.path.dirname(__file__), "evaluation_report.json")
    with open(report_path, "w") as f:
        json.dump(report, f, indent=2)
    print(f"Detailed evaluation report saved to {report_path}")

if __name__ == "__main__":
    run_evaluation()
